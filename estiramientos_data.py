def cargar_catalogo_estiramientos(conn):
    """Inserta el catálogo de estiramientos si la tabla está vacía."""
    total = conn.execute("SELECT COUNT(*) FROM estiramientos").fetchone()[0]
    if total > 0:
        return 0
    for ejercicio in CATALOGO:
        conn.execute(
            "INSERT INTO estiramientos "
            "(grupo, numero, nombre, descripcion, musculos, variantes, "
            "observaciones, atencion, rotulos, pagina_original, imagen) "
            "VALUES (:grupo, :numero, :nombre, :descripcion, :musculos, "
            ":variantes, :observaciones, :atencion, :rotulos, "
            ":pagina_original, :imagen)",
            ejercicio,
        )
    return len(CATALOGO)
